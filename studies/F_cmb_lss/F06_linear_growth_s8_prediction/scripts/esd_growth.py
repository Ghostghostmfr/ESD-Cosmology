def linear_growth_g_typical(sigma8=SIGMA8_PLANCK, R_mpc_h=8.0, h=0.6736,
                             omega_m=OMEGA_M_LOCK):
    """Heuristic acceleration at the edge of an 8 Mpc/h linear sphere.

    Used only to *quantify how large R(u) WOULD have been* if axiom (A1)
    had held — to show the open item from Study 18 is genuinely closed
    by the applicability theorem (the alternative interpretation would
    have given catastrophic enhancement).
    """
    R_m = R_mpc_h * MPC_M / h
    rho_crit_0 = 3.0 * H_PLANCK**2 / (8.0 * math.pi * G_SI)
    rho_mean   = rho_crit_0 * omega_m
    # mass enclosed in a sphere of radius R with mean overdensity ~ sigma8
    M = (4.0/3.0) * math.pi * R_m**3 * rho_mean * sigma8
    g = G_SI * M / R_m**2
    u = 4.0 * g / A0_SI
    R = R_of_u(u)
    return {"R_m": R_m, "g": g, "u": u, "R_of_u_naive": R,
            "would_have_boosted_sigma8_by": math.sqrt(1.0 + R)}
