def S8_ESD(sigma8_planck=SIGMA8_PLANCK):
    """ESD-predicted S_8 = sigma_8 * sqrt(Omega_m / 0.3)."""
    return sigma8_ESD(sigma8_planck) * math.sqrt(OMEGA_M_LOCK / 0.3)

