from __future__ import annotations
import math
from esd_core import OMEGA_M_LOCK, a_zero

H0_PLANCK_KMS = 67.36
A0_SI         = a_zero(H0_PLANCK_KMS)

# Planck 2018 linear amplitude (TT,TE,EE+lowE+lensing)
SIGMA8_PLANCK     = 0.8111
SIGMA8_PLANCK_ERR = 0.0060

# closure-pool constants
PHI   = (1 + math.sqrt(5)) / 2
P_EXP = PHI
Q_EXP = 2*math.log(PHI)/PHI
C_FLR = (4*math.log(PHI) - 1)/PHI
B_AMP = PHI**6 - 2
S_NRM = 16*PHI + 1

G_SI    = 6.67430e-11
MSUN_KG = 1.98892e30
MPC_M   = 3.0856775814913673e22
H_PLANCK = H0_PLANCK_KMS * 1000 / MPC_M    # s^-1

def Sigma(u): return u**P_EXP + B_AMP*u**Q_EXP + C_FLR
def R_of_u(u): return S_NRM / Sigma(u)

def applicability_test_linear_perturbation():
    """Verify axiom (A1) fails for a linear cosmological perturbation.

    Returns a dict of (axiom, passes_axiom).  R(u) applies only when
    ALL THREE axioms hold.  We return that (A1) fails for linear modes.
    """
    return {
        "A1_bound_system_locality":  False,    # delta and background are same field
        "A2_acceleration_definedness": "ambiguous",  # phi_pert not separable from phi_bg
        "A3_closure_universality":   True,     # universal IF A1,A2 hold
        "Ru_applies":                False,
        "rationale": (
            "delta(x,t) is a fluctuation of the same matter field that "
            "constitutes the background; no system/spectator split exists "
            "at linear order, so axiom (A1) fails."
        ),
    }

